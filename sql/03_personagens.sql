CREATE TABLE PERSONAGENS (
    ID_PERSONAGEM NUMBER(10) NOT NULL,
    NOME VARCHAR 2(30) NOT NULL,
    CLASSE VARCHAR2(20) NOT NULL,
    NIVEL NUMBER(3) NOT NULL,
    ID_JOGADOR NUMBER(10) NOT NULL,
    ID_GUILDA NUMBER(10) NOT NULL,
    CONSTRAINT PERSONAGENS_PK PRIMARY KEY (ID_PERSONAGEM),
    CONSTRAINT PERSONAGENS_CLASSE_CK CHECK (CLASSE IN('Guerreiro', 'Mago', 'Arqueiro', 'Sacerdote')),
    CONSTRAINT PERSONAGENS_NIVEL_CK CHECK (NIVEL BETWEEN 1 AND 100)
);

CREATE SEQUENCE PERSONAGENS_ID_SEQ;

ALTER TABLE PERSONAGENS ADD CONSTRAINT JOGADORES_PERSONAGENS_FK
    FOREIGN KEY (ID_JOGADOR) REFERENCES JOGADORES(ID_JOGADOR);

ALTER TABLE PERSONAGENS ADD CONSTRAINT GUILDAS_PERSONAGENS_FK
    FOREIGN KEY (IS_JOGADOR) REFERENCES JOGADORES (ID_JOGADOR);

